#!/usr/bin/env python3
"""Generate the predecoder table's numeric macros from verified integer time/count evidence."""
import argparse
from decimal import Decimal, ROUND_HALF_UP, localcontext
import hashlib
import json
from pathlib import Path
import re
import sys

import migrate_paper_numbers as M
import tailreset_data as D

HERE = Path(__file__).resolve().parent
VARIANTS = {'none': 'skip', 'coordinate': 'coordinate', 'degree-ordered': 'degree'}
MARKER = '% Generated by generate_predecoder_macros.py; do not edit numeric values.\n'


def need(ok, message):
    if not ok:
        raise ValueError(message)


def integer(value, label, positive=False):
    need(type(value) is int and value >= (1 if positive else 0), 'Invalid integer ' + label)
    return value


def config_check(config):
    need(config['schema_version'] == 1 and config['variants'] == VARIANTS, 'Unconfirmed predecoder strategy mapping')
    need(config['distances'] == [9, 13, 17, 21, 25, 29, 33] and
         Decimal(config['physical_error_rate']) == Decimal('.003'), 'Need the complete p=0.003 matrix')
    need(config['shots'] == 1_000_000 and config['batch_repeats'] == 3, 'Need three million-shot batch passes')
    need(config['namespace'] == 'xeon.predecoder-comparison' and config['decimal_places'] == 2, 'Unexpected macro namespace or precision')


def calculate(summary, config):
    """Use elapsed_ns and syndrome totals; cached floating means/percentages are never operands."""
    config_check(config)
    for field in ['experiment_id', 'implementation_commit', 'acquisition_commit']:
        need(summary[field] == config[field], 'Unexpected source identity: ' + field)
    calls = {}
    for call in summary['calls']:
        key = call['case'], call['method'], call['phase'], call['repeat']
        need(key not in calls, 'Duplicate call: ' + str(key))
        calls[key] = call
    # The verified export fixes each case's distance and probability.
    cases = {}
    for call in summary['calls']:
        need(Decimal(str(call['p'])) == Decimal(config['physical_error_rate']), 'Mixed physical error rates')
        d = call['d']
        need(d in config['distances'] and cases.get(d, call['case']) == call['case'], 'Duplicate/unexpected case')
        cases[d] = call['case']
    need(set(cases) == set(config['distances']), 'Incomplete distance matrix')
    values = {}
    rates = []
    with localcontext() as ctx:
        ctx.prec = 60
        for d in config['distances']:
            case = cases[d]
            initial = calls[(case, 'skip', 'statistics', 1)]
            n0 = integer(initial['normalized'], 'initial syndromes', True)
            need(initial['residual'] == n0, 'No-predecoder residual must equal initial count')
            for alias, method in config['variants'].items():
                batches = [calls[(case, method, 'batch', r)] for r in range(1, 4)]
                stat = calls[(case, method, 'statistics', 1)]
                need(all(integer(c['shots'], 'shots', True) == config['shots'] for c in batches + [stat]), 'Incomplete shot count')
                elapsed = sum(integer(c['elapsed_ns'], 'batch ns', True) for c in batches)
                measured = sum(c['shots'] for c in batches)
                norm = integer(stat['normalized'], 'normalized syndromes', True)
                residual = integer(stat['residual'], 'remaining syndromes')
                need(norm == n0 and residual <= norm, 'Strategies must share the same normalized inputs')
                matched = sum(2 * integer(c['pairs'], 'pairs') + integer(c['boundaries'], 'boundaries')
                              for c in stat['components'])
                need(matched == norm - residual, 'Matched/residual seed conservation differs')
                prefix = f"{config['namespace']}.d{d}.p0p3.{alias}."
                values[prefix + 'mean-time-us'] = dict(value=Decimal(elapsed) / Decimal(measured) / 1000,
                    unit='us/shot', formula='sum(batch elapsed_ns) / sum(batch shots) / 1000',
                    operands=dict(elapsed_ns=[c['elapsed_ns'] for c in batches], shots=measured,
                                  validations=[c['validation'] for c in batches]))
                values[prefix + 'mean-remaining-syndromes'] = dict(value=Decimal(residual) / Decimal(stat['shots']),
                    unit='syndromes/shot', formula='residual total / statistics shots',
                    operands=dict(residual_total=residual, shots=stat['shots'], validation=stat['validation']))
                if alias != 'none':
                    rate = Decimal(matched) / Decimal(n0) * 100
                    key = prefix + 'matched-percent'
                    values[key] = dict(value=rate, unit='percent', formula='100 * (initial total - residual total) / initial total',
                        operands=dict(initial_total=n0, residual_total=residual, matched_total=matched,
                                      initial_validation=initial['validation'], validation=stat['validation']))
                    if alias == 'degree-ordered': rates.append((rate, d, key))
        for label, selected in [('min', min(rates)), ('max', max(rates))]:
            raw, distance, key = selected
            values[f"{config['namespace']}.p0p3.degree-ordered.matched-percent.{label}"] = dict(
                value=raw, unit='percent', formula=label + '(unrounded degree-ordered matched percentages)',
                operands=dict(distance=distance, selected_key=key, distances=config['distances']))
    need(len(values) == 58, 'Expected 56 table values and two narrative range bounds')
    return values


def format_value(value):
    with localcontext() as ctx:
        ctx.prec = 60
        return format(value.quantize(Decimal('.01'), rounding=ROUND_HALF_UP), '.2f')


def render(values, manifest_sha):
    preamble = r"""% Load paper_num_template.tex in the preamble before this file.
% Values: current T4 TailReset, p=0.3%, LTO OFF; three million-shot batch passes.
% Counts: separate untimed pipeline replay; percentages use unrounded integer totals.
% Units and percent signs remain in the manuscript. All values use two decimal places.
\ifdefined\BBPredecoderNumbersLoaded\expandafter\endinput\fi
\ifdefined\DefinePerfValue\else
  \PackageError{predecoder-numbers}{Load paper_num_template.tex before predecoder_numbers.tex}
    {The shared DefinePerfValue and PerfValue commands must be defined in the preamble.}
  \expandafter\endinput
\fi
\newcommand{\BBPredecoderNumbersLoaded}{}

"""
    return (MARKER + '% Verified TailReset SOURCE.json SHA256: ' + manifest_sha + '\n' + preamble +
            ''.join('\\DefinePerfValue{' + key + '}{' + format_value(item['value']) + '}\n'
                    for key, item in values.items()))


def build(config_path):
    config_path = Path(config_path).resolve()
    config = json.loads(config_path.read_text())
    config_check(config)
    spec = config['manifest']
    manifest_path = (config_path.parent / spec['path']).resolve()
    need(M.digest(manifest_path) == spec['sha256'], 'TailReset SOURCE.json SHA256 differs')
    summary = D.verify(manifest_path)
    values = calculate(summary, config)
    manifest = json.loads(manifest_path.read_text())
    protected = {config_path, manifest_path, Path(__file__).resolve(), Path(D.__file__).resolve(),
                 Path(M.__file__).resolve(), HERE / 'paper_num_template.tex'}
    protected.update((manifest_path.parent / ref['path']).resolve() for ref in manifest['files'].values())
    protected.update((manifest_path.parent / ref['path']).resolve() for ref in manifest['exports'].values())
    protected.add(HERE / 'data/predecode.csv')
    return render(values, spec['sha256']), values, config, manifest_path, protected


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path, default=HERE / 'predecoder_macro_source.json')
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--output', type=Path, help='Write generated macros and a provenance audit; existing generated files can be refreshed')
    mode.add_argument('--check', action='store_true', help='Verify committed numbers without writing')
    parser.add_argument('--numbers', type=Path, default=HERE / 'predecoder_numbers.tex', help='File compared by --check')
    parser.add_argument('--manuscript', type=Path, help='Optionally verify all 58 macro references in a separate manuscript with --check')
    parser.add_argument('--audit', type=Path, help='Default: <output>.audit.json')
    args = parser.parse_args(argv)
    try:
        text, values, config, manifest, protected = build(args.config)
        need(args.manuscript is None or args.check, '--manuscript requires --check')
        if args.check:
            need(args.numbers.read_bytes() == text.encode(), 'Generated macros are stale; regenerate --output')
            if args.manuscript is not None:
                used = set(re.findall(r'\\PerfValue\{([^{}]+)\}', args.manuscript.read_text()))
                need(used == set(values), 'Manuscript references differ from the 58 generated keys')
        else:
            target = args.output.resolve()
            audit = args.audit.resolve() if args.audit else target.with_name(target.name + '.audit.json')
            need(target != audit and target not in protected and audit not in protected, 'Output/audit would overwrite source or evidence')
            need(target.parent.is_dir() and audit.parent.is_dir(), 'Output directory must already exist')
            if target.exists(): need(target.read_text().startswith(MARKER), 'Refusing to overwrite a file not generated by this script')
            if audit.exists():
                need(json.loads(audit.read_text()).get('generator') == Path(__file__).name, 'Refusing to overwrite an unrelated audit file')
            record = dict(complete=True, generator=Path(__file__).name, script=M.reference(__file__),
                source=M.reference(manifest), config=M.reference(args.config),
                experiment_id=config['experiment_id'], implementation_commit=config['implementation_commit'],
                rounding='Decimal precision 60; final ROUND_HALF_UP to two decimal places',
                output=dict(path=str(target), sha256=hashlib.sha256(text.encode()).hexdigest()),
                values={key:dict(item, value=str(item['value']), formatted=format_value(item['value'])) for key,item in values.items()})
            M.atomic_write(audit, M.json_text(record).encode())
            M.atomic_write(target, text.encode())
        print('Verified 58 predecoder macros (56 table entries and two narrative bounds).')
        for key, item in values.items():
            if '.d33.' in key or key.endswith(('.min', '.max')): print(key + ' = ' + format_value(item['value']))
        return 0
    except (OSError, ValueError, KeyError, TypeError, M.MigrationError) as error:
        print('Predecoder macro generation failed: ' + str(error), file=sys.stderr)
        return 2


if __name__ == '__main__': raise SystemExit(main())
